#!/usr/bin/env python3
"""Parse README.md paper tables and generate docs/data.js for the GitHub Pages site.

Usage: python3 scripts/build_data.py
README.md remains the single source of truth; re-run this script after updating it.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
README = ROOT / "README.md"
OUT = ROOT / "docs" / "data.js"

ROW_RE = re.compile(r"^\|(.+)\|$")
LINK_RE = re.compile(r"\[(📄 Paper|💻 Code)\]\(([^)]+)\)")

# Venue family -> display color (curated palette)
VENUE_COLORS = {
    "ICLR": "#7C3AED",
    "ICML": "#EA580C",
    "NeurIPS": "#059669",
    "CVPR": "#2563EB",
    "ICCV": "#0891B2",
    "ECCV": "#DB2777",
    "AAAI": "#DC2626",
    "IJCAI": "#C2410C",
    "ACM MM": "#4F46E5",
    "ACL": "#65A30D",
    "WACV": "#0284C7",
    "BMVC": "#0D9488",
    "ICASSP": "#D97706",
    "ICIP": "#CA8A04",
    "ICME": "#16A34A",
    "TPAMI": "#0F172A",
    "TIP": "#334155",
    "TMM": "#334155",
    "TCSVT": "#334155",
    "TCVST": "#334155",
    "IJCV": "#0F766E",
    "IJMLC": "#0F766E",
    "TVCJ": "#0F766E",
    "PR": "#0F766E",
    "TMLR": "#6D28D9",
}
DEFAULT_COLOR = "#78716C"  # warm gray for smaller venues


def norm_venue(raw: str) -> str:
    """'CVPR'2026 Findings' -> 'CVPR'; 'NeurIPS'2025 D&B' -> 'NeurIPS'; 'ACM MM'2025' -> 'ACM MM'"""
    return raw.split("'")[0].strip()


def parse():
    papers = []
    year = None
    for line in README.read_text(encoding="utf-8").splitlines():
        m = re.match(r"^## (20\d\d)\s*$", line)
        if m:
            year = int(m.group(1))
            continue
        if year is None or not ROW_RE.match(line.strip()):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) != 4 or cells[0].lower() in ("method", ":---:", "---"):
            continue
        method, title, venue_raw, links = cells
        paper_url = code_url = None
        for label, url in LINK_RE.findall(links):
            if "Paper" in label:
                paper_url = url
            elif "Code" in label:
                code_url = url
        family = norm_venue(venue_raw)
        papers.append({
            "year": year,
            "method": "" if method == "—" else method,
            "title": title,
            "venue": venue_raw,
            "venueFamily": family,
            "color": VENUE_COLORS.get(family, DEFAULT_COLOR),
            "paper": paper_url,
            "code": code_url,
        })
    return papers


def main():
    papers = parse()
    venues = sorted({p["venueFamily"] for p in papers})
    years = sorted({p["year"] for p in papers}, reverse=True)
    payload = {"papers": papers, "venues": venues, "years": years}
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(
        "// Auto-generated by scripts/build_data.py — do not edit by hand.\n"
        "const DATA = " + json.dumps(payload, ensure_ascii=False, indent=2) + ";\n",
        encoding="utf-8",
    )
    with_code = sum(1 for p in papers if p["code"])
    print(f"Parsed {len(papers)} papers ({with_code} with code), "
          f"{len(venues)} venue families, years {years}")
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
